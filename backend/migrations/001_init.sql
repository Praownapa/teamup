-- TeamUp database schema, version 1.
-- Conventions: ids are identity integers; text columns default to '' rather than NULL;
-- times are timestamptz. Applied automatically on app startup (see app/db.py run_migrations).

-- ---------------------------------------------------------------- people
CREATE TABLE users (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cognito_sub        text UNIQUE,                       -- Cognito's user id; NULL for demo/dev users
  email              text NOT NULL UNIQUE CHECK (email = lower(email)),
  name               text NOT NULL DEFAULT '',
  student_id         text NOT NULL DEFAULT '',          -- text, so leading zeros survive
  major              text NOT NULL DEFAULT '',
  year               smallint NOT NULL DEFAULT 1 CHECK (year BETWEEN 1 AND 6),
  role               text NOT NULL DEFAULT 'student' CHECK (role IN ('student', 'admin')),
  status             text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended')),
  bio                text NOT NULL DEFAULT '',
  portfolio          text NOT NULL DEFAULT '',
  open_to_projects   boolean NOT NULL DEFAULT true,     -- false = hidden from teammate recommendations
  notify_invitations boolean NOT NULL DEFAULT true,     -- email preferences (stored; email sending is not built yet)
  notify_requests    boolean NOT NULL DEFAULT true,
  notify_team        boolean NOT NULL DEFAULT true,
  notify_digest      boolean NOT NULL DEFAULT false,
  created_at         timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE user_skills (
  user_id  integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  name     text NOT NULL,
  level    text NOT NULL DEFAULT 'Beginner' CHECK (level IN ('Beginner', 'Intermediate', 'Advanced')),
  position smallint NOT NULL DEFAULT 0                  -- display order
);
CREATE UNIQUE INDEX user_skills_unique ON user_skills (user_id, lower(name));

CREATE TABLE user_interests (
  user_id  integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  name     text NOT NULL,
  position smallint NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX user_interests_unique ON user_interests (user_id, lower(name));

-- ---------------------------------------------------------------- projects and teams
CREATE TABLE categories (
  name       text PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now()         -- list order
);
CREATE UNIQUE INDEX categories_name_ci ON categories (lower(name));

CREATE TABLE projects (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id    integer NOT NULL REFERENCES users (id),
  title       text NOT NULL,
  description text NOT NULL,
  category    text NOT NULL,                            -- a label: deleting a category keeps existing labels
  course      text NOT NULL DEFAULT '',
  cover_url   text NOT NULL DEFAULT '',
  max_size    smallint NOT NULL CHECK (max_size BETWEEN 2 AND 10),   -- including the owner
  accepting   boolean NOT NULL DEFAULT true,            -- false = recruitment paused (invitations still allowed)
  deadline    date,
  duration    text NOT NULL DEFAULT '',
  meeting     text NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now(),
  removed_at  timestamptz                               -- set when an admin removes the project
);
CREATE INDEX projects_owner ON projects (owner_id);

CREATE TABLE project_skills (
  project_id integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  name       text NOT NULL,
  position   smallint NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX project_skills_unique ON project_skills (project_id, lower(name));

-- One row per place in a team. user_id NULL = an open spot; the team is the rows that have a user_id.
CREATE TABLE project_roles (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  name       text NOT NULL,
  user_id    integer REFERENCES users (id),
  position   smallint NOT NULL DEFAULT 0
);
CREATE INDEX project_roles_project ON project_roles (project_id);
CREATE INDEX project_roles_user ON project_roles (user_id);
-- A person can hold at most one place in a project.
CREATE UNIQUE INDEX project_roles_one_place_per_member ON project_roles (project_id, user_id) WHERE user_id IS NOT NULL;

-- Join requests (kind 'request', started by a student) and invitations (kind 'invitation', started by the owner).
CREATE TABLE requests (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id   integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  user_id      integer NOT NULL REFERENCES users (id),  -- the student: applicant or invitee
  by_id        integer REFERENCES users (id),           -- who sent an invitation; NULL for join requests
  kind         text NOT NULL CHECK (kind IN ('request', 'invitation')),
  role         text NOT NULL,
  message      text NOT NULL DEFAULT '',
  status       text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'rejected')),
  created_at   timestamptz NOT NULL DEFAULT now(),
  responded_at timestamptz
);
CREATE INDEX requests_project_status ON requests (project_id, status);
CREATE INDEX requests_user ON requests (user_id);
-- At most one pending request or invitation per person per project.
CREATE UNIQUE INDEX requests_one_pending_per_person ON requests (project_id, user_id) WHERE status = 'pending';

CREATE TABLE saved_projects (
  user_id    integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  project_id integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, project_id)
);

CREATE TABLE reports (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id  integer NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  reporter_id integer NOT NULL REFERENCES users (id),
  reason      text NOT NULL,
  status      text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'removed', 'dismissed')),
  created_at  timestamptz NOT NULL DEFAULT now(),
  resolved_at timestamptz,
  resolved_by integer REFERENCES users (id)
);
CREATE UNIQUE INDEX reports_one_open_per_reporter ON reports (project_id, reporter_id) WHERE status = 'open';

CREATE TABLE notifications (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,   -- the recipient
  kind       text NOT NULL CHECK (kind IN ('request', 'invite', 'accepted', 'declined', 'team', 'match')),
  text       text NOT NULL,
  request_id integer REFERENCES requests (id) ON DELETE CASCADE,         -- set when the user can act on it
  unread     boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX notifications_user_created ON notifications (user_id, created_at DESC);

-- ---------------------------------------------------------------- derived data
-- Team size and status of every project: 'full' when members >= max_size, otherwise
-- 'recruiting' when accepting join requests, otherwise 'closed'.
CREATE VIEW project_summary AS
  SELECT p.id AS project_id,
         count(r.user_id)::int AS member_count,
         count(r.id)::int AS place_count,
         CASE WHEN count(r.user_id) >= p.max_size THEN 'full'
              WHEN p.accepting THEN 'recruiting'
              ELSE 'closed' END AS status
  FROM projects p
  LEFT JOIN project_roles r ON r.project_id = p.id
  GROUP BY p.id;

-- Match score 0-100: the share of a project's required skills that a user has
-- (case-insensitive exact names), rounded half-up like JavaScript Math.round.
-- 0 when the project lists no skills.
CREATE FUNCTION match_score(p_project_id integer, p_user_id integer) RETURNS integer
LANGUAGE sql STABLE AS $$
  SELECT CASE WHEN count(*) = 0 THEN 0
              ELSE floor(100.0 * count(us.user_id) / count(*) + 0.5)::int END
  FROM project_skills ps
  LEFT JOIN user_skills us ON us.user_id = p_user_id AND lower(us.name) = lower(ps.name)
  WHERE ps.project_id = p_project_id
$$;

